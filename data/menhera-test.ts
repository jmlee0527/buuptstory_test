export const menheraQuestions: MenheraQuestion[] = menheraDomainOrder.flatMap((domain, domainIndex) => scenarios[domain].map((text, index) => {
  const reverseScored = index % 4 === 1;
  const labels = optionSets[domain][index % optionSets[domain].length];
  const severityOptions = labels.map((label, severity) => ({ label, value: reverseScored ? 3 - severity : severity }));
  const order = permutations[(index + domainIndex * 3) % permutations.length];
  return {
    id: `mh-${String(domainIndex + 1).padStart(2, "0")}-${String(index + 1).padStart(2, "0")}`,
    domain,
    text,
    reverseScored,
    options: order.map((optionIndex) => severityOptions[optionIndex]) as MenheraQuestion["options"],
  };
}));

